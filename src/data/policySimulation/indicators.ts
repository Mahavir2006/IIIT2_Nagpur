const INDEX = new Map(INDICATORS.map((i) => [i.id, i]));

export const indicatorById = (id: string): Indicator | undefined => INDEX.get(id);
export const indicatorsByIds = (ids: string[]): Indicator[] =>
  ids.map((id) => INDEX.get(id)).filter((i): i is Indicator => !!i);
export const indicator = (id: string): Indicator => {
  const found = INDEX.get(id);
  if (!found) throw new Error(`Unknown indicator: ${id}`);
  return found;
};
