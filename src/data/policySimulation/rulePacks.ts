export const RULE_PACKS: RulePack[] = [
  CONVERSION,
  RECORDS,
  TENANCY,
  PLANNING,
  INDUSTRY,
  LOGISTICS,
  ACQUISITION,
];

const PACK_INDEX = new Map(RULE_PACKS.map((p) => [p.id, p]));

export const rulePackById = (id: string | undefined): RulePack | undefined =>
  id ? PACK_INDEX.get(id) : undefined;

/** Land classes a pack is allowed to act on — drives the picker's option list. */
export const packLandCategories = (pack: RulePack): LandCategoryId[] => {
  const seen = new Set<LandCategoryId>();
  for (const rule of pack.rules) {
    if (rule.target.kind === "land") seen.add(rule.target.category);
    if (rule.fromLand) seen.add(rule.fromLand);
    for (const s of rule.spillover ?? []) seen.add(s.category);
  }
  return [...seen];
};

/**
 * Pick the pack that best matches a set of free-text terms. Used to attach an
 * uploaded PDF to a rule set: the document supplies the figures, the pack
 * supplies the mechanics.
 */
export function matchRulePack(text: string): { pack: RulePack; score: number } | null {
  const haystack = text.toLowerCase();
  let best: { pack: RulePack; score: number } | null = null;
  for (const pack of RULE_PACKS) {
    let score = 0;
    for (const kw of pack.keywords) {
      const hits = haystack.split(kw).length - 1;
      // A long phrase is a stronger signal than a single common word.
      score += (hits * Math.min(kw.length, 12)) / 4;
    }
    if (!best || score > best.score) best = { pack, score };
  }
  return best && best.score > 0 ? best : null;
}
