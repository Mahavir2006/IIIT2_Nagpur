import type { EffectRule, LandCategoryId, ParamValues, PolicyParameter } from "./types";

/**
 * Rule packs — the reusable effect model behind every policy.
 *
 * A rule pack owns a parameter set and the rules that turn those parameters
 * into movement in land classes and indicators. A policy in `library/` supplies
 * the citation, the dates, the geographies and — critically — the *evidence*
 * for each parameter value; the pack supplies the mechanics.
 *
 * Splitting the two is what makes a 14-instrument library tractable: without
 * it every policy would need its own hand-written copy of the same elasticities,
 * and the 14 sets would drift apart. With it, a stated figure such as
 * "conversion not permitted within 50 m of a watercourse" becomes a parameter
 * default carrying a page-and-clause citation, and the pack's rule does the
 * arithmetic.
 *
 * The elasticities here are illustrative, not estimated. Each rule's `note` is
 * rendered verbatim in the Assumptions panel so a reader always sees the
 * reasoning that produced a number.
 */

export interface RulePackPreset {
  id: string;
  name: string;
  description: string;
  overrides: ParamValues;
}

export interface RulePack {
  id: string;
  label: string;
  description: string;
  /**
   * Terms that indicate an uploaded document belongs to this family. Used to
   * pick a pack for a policy the user uploads as a PDF.
   */
  keywords: string[];
  /** domain label applied to any policy built on this pack without an override */
  domain: string;
  parameters: PolicyParameter[];
  rules: EffectRule[];
  presets: RulePackPreset[];
}

