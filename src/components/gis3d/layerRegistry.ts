const LAYER_INDEX = new Map(GIS_LAYERS.map((l) => [l.id, l]));

export function gisLayer(id: string): GisLayerDef | undefined {
  return LAYER_INDEX.get(id);
}

export const DEFAULT_LAYER_IDS: string[] = GIS_LAYERS.filter(
  (l) => l.defaultOn && l.status !== "unavailable",
).map((l) => l.id);

/** Layers that are listed but cannot be switched on. */
export const UNAVAILABLE_LAYER_IDS: string[] = GIS_LAYERS.filter(
  (l) => l.status === "unavailable",
).map((l) => l.id);

/** True when a layer has a source we are allowed to draw. */
export function isDrawable(id: string): boolean {
  const l = LAYER_INDEX.get(id);
  return !!l && l.status !== "unavailable";
}

/** Sentinel-2 mosaic years — same list the 2D maps use. */
export const TIME_YEARS: number[] = [2018, 2019, 2020, 2021, 2022, 2023, 2024];

