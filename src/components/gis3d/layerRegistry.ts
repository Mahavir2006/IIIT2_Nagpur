/**
 * The layer manager's source of truth: every checkbox the 3D GIS Explorer can
 * show, its render path, its legend and — most importantly — its provenance.
 *
 * `status` is not decoration:
 *   "connected"  real, wired data source rendered on the globe
 *   "demo"       rendered, but from in-repo demo/modelled aggregates — labelled
 *   "unavailable"no dataset is wired; the UI must say so instead of inventing
 *
 * Sources referenced here are the same ones already documented in
 * src/data/data-sources.ts and the README data-sources table.
 */
